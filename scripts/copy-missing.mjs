// ก๊อปรูปจริงจาก dataset สำหรับรหัสที่ CDN ไม่มี (CDN ส่งรูปหลังการ์ด 404) → public/cards/{code}.png
// รันหลัง check-cdn.mjs: node scripts/copy-missing.mjs
import { readFileSync, copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const SRC = 'D:/pokemon_dataset_ready/content/pokemon_dataset_temp';
const miss = new Set(JSON.parse(readFileSync('scripts/cdn-missing.json', 'utf8')));

const path = {};
for (const d of readdirSync(SRC, { withFileTypes: true })) {
  if (!d.isDirectory()) continue;
  for (const f of readdirSync(`${SRC}/${d.name}`)) {
    const c = f.replace(/\.png$/i, '');
    if (miss.has(c)) path[c] = `${SRC}/${d.name}/${f}`;
  }
}

// ไฟล์ที่ hash ซ้ำกันหลายใบ = รูปหลังการ์ดใน dataset เอง ไม่มีรูปจริง
const hash = {};
const byHash = {};
for (const [c, p] of Object.entries(path)) {
  hash[c] = createHash('md5').update(readFileSync(p)).digest('hex');
  byHash[hash[c]] = (byHash[hash[c]] || 0) + 1;
}

mkdirSync('public/cards', { recursive: true });
const local = [], noImage = [];
for (const c of miss) {
  if (!path[c] || byHash[hash[c]] > 1) { noImage.push(c); continue; }
  copyFileSync(path[c], `public/cards/${c}.png`);
  local.push(c);
}

writeFileSync('src/lib/cdnMissing.js',
  `// generated by scripts/copy-missing.mjs — อย่าแก้มือ\n` +
  `export const localCodes = new Set(${JSON.stringify(local.sort())});\n` +
  `export const noImageCodes = new Set(${JSON.stringify(noImage.sort())});\n`);
console.log(`local: ${local.length}, no image: ${noImage.length}`);
